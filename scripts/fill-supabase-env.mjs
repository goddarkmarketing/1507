/**
 * Fill .env.local from CLI once you have Supabase keys.
 *
 * Usage:
 *   node scripts/fill-supabase-env.mjs --url https://xxx.supabase.co --anon eyJ...
 *
 * Optional:
 *   --webhook https://discord.com/api/webhooks/...
 *   --site https://www.krabilinkstaxi.com
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : "";
}

const url = (arg("url") || "").trim();
const anon = (arg("anon") || "").trim();
const webhook = (arg("webhook") || "").trim();
const site = (arg("site") || "https://www.krabilinkstaxi.com").trim();

if (!url || !anon) {
  console.error(`
Missing keys.

1) Open https://supabase.com → New project
2) SQL Editor → run supabase/migrations/001_bookings.sql
3) SQL Editor → run supabase/SETUP_SECRET.sql
4) Settings → API → copy Project URL + anon public key
5) Run:

   node scripts/fill-supabase-env.mjs --url "https://YOUR.supabase.co" --anon "eyJ..."

Then add the same values as GitHub Actions secrets and push master.
`);
  process.exit(1);
}

const envPath = resolve(process.cwd(), ".env.local");
let secret = "5Ov2jW8z4GY-9xc55wBgA7XKsAS9o6QUXLisjkzHkuQ";
if (existsSync(envPath)) {
  const prev = readFileSync(envPath, "utf8");
  const m = prev.match(/^NEXT_PUBLIC_BOOKING_ADMIN_SECRET=(.*)$/m);
  if (m?.[1]?.trim()) secret = m[1].trim();
}

const body = `# Generated by scripts/fill-supabase-env.mjs
NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}
NEXT_PUBLIC_BOOKING_ADMIN_SECRET=${secret}
NEXT_PUBLIC_SITE_URL=${site}
NEXT_PUBLIC_ADMIN_NOTIFY_WEBHOOK=${webhook}
`;

writeFileSync(envPath, body, "utf8");
console.log("Wrote .env.local");
console.log("Restart: npm run dev");
console.log(`
GitHub → Settings → Secrets and variables → Actions — set:
  NEXT_PUBLIC_SUPABASE_URL
  NEXT_PUBLIC_SUPABASE_ANON_KEY
  NEXT_PUBLIC_BOOKING_ADMIN_SECRET
  NEXT_PUBLIC_SITE_URL
  NEXT_PUBLIC_ADMIN_NOTIFY_WEBHOOK (optional)
Then: git push origin master
`);
